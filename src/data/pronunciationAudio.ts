export function getPronunciationAudioUrl(nameId: number): string | null {
  if (!Number.isInteger(nameId) || nameId < 1 || nameId > 98) return null;
  const sourceClipNumber = nameId <= 66 ? nameId : nameId + 1;
  const filename = AUDIO_FILES[sourceClipNumber - 1];
  return filename ? AUDIO_BASE + encodeURIComponent(filename) : null;
}
